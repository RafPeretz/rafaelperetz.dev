#!/usr/bin/env node
/**
 * Generates public/logos.svg: one <symbol> per technology logo from simple-icons.
 * Pages reference it with <svg><use href="/logos.svg#kubernetes"/></svg>, so the paths are
 * downloaded once and cached instead of being inlined (twice: HTML + RSC payload) in every page.
 *
 *   node scripts/build-logos.mjs   (re-run after changing SIMPLE_ICONS below; the output is committed)
 */
import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

// Keys must match BRAND_LOGOS in src/content-icons.ts (Azure/AWS are drawn with Phosphor glyphs instead).
const SIMPLE_ICONS = {
  kubernetes: si.siKubernetes,
  docker: si.siDocker,
  githubactions: si.siGithubactions,
  python: si.siPython,
  fastapi: si.siFastapi,
  react: si.siReact,
  nextdotjs: si.siNextdotjs,
  typescript: si.siTypescript,
  nodedotjs: si.siNodedotjs,
  postgresql: si.siPostgresql,
  supabase: si.siSupabase,
  railway: si.siRailway,
  vercel: si.siVercel,
};

const symbols = Object.entries(SIMPLE_ICONS)
  .map(
    ([id, icon]) =>
      `  <symbol id="${id}" viewBox="0 0 24 24"><title>${icon.title}</title><path d="${icon.path}"/></symbol>`,
  )
  .join("\n");

writeFileSync(
  new URL("../public/logos.svg", import.meta.url),
  `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Generated by scripts/build-logos.mjs from simple-icons (CC0). Do not edit. -->\n${symbols}\n</svg>\n`,
);
console.log(`public/logos.svg: ${Object.keys(SIMPLE_ICONS).length} symbols`);
